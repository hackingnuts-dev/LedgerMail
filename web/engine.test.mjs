import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const E=createRequire(import.meta.url)('./engine.js');
const msg=(id,subject,snippet,date='2026-11-08T15:00:00Z')=>({id,subject,snippet,date,sender:'Merchant <billing@example.com>'});
assert.equal(E.parseEmail(msg('otp','OTP for your Federal credit card transaction','Payment of $500.00 code 456123')),null,'OTP messages must not be payment transactions');
assert.equal(E.parseEmail(msg('x','Security code','Your payment is $50')),null,'security email ignored');
const receipt=E.parseEmail(msg('r','Payment received - receipt #552','We received your payment of $285.00'));
assert.equal(receipt.kind,'PAYMENT');assert.equal(receipt.amount,285);assert.equal(receipt.status,'REVIEW');assert.equal(receipt.suggestedStatus,'LIKELY_PAID');
const bill=E.parseEmail(msg('b','Statement ready','Amount due $93.25 payment due date 12/15/2026'));
assert.equal(bill.kind,'BILL');assert.equal(bill.dueDate,'2026-12-15');assert.equal(bill.status,'REVIEW');assert.equal(bill.suggestedStatus,'POSSIBLY_DUE');
assert.equal(E.parseEmail(msg('p','Sale','Enjoy our $10 discount')),null);
assert.equal(E.parseEmail(msg('un','Receipt','Paid ₹1,299.00')).currency,'INR');
assert.equal(E.parseEmail(msg('other','Order completed','Paid $50.00')).amount,50);
assert.equal(E.normalizeStatus('CONFIRMED'),'PAID');assert.equal(E.normalizeStatus('UNPAID'),'DUE');
assert.equal(E.reviewTransition('REVIEW','PAID'),'PAID');
assert.throws(()=>E.reviewTransition('PAID','SURPRISE'),/Illegal/);
assert.equal(E.transition('auth','CONNECTING','VERIFYING'),'VERIFYING');
assert.throws(()=>E.transition('auth','DISCONNECTED','CONNECTED'),/Illegal/);
assert.throws(()=>E.transition('sync','IDLE','COMPLETE'),/Illegal/);
assert.equal(E.transition('navigation','dashboard','payments'),'payments');
assert.throws(()=>E.transition('navigation','dashboard','not-a-page'),/Illegal/);
assert.equal(E.transition('inbox','LOADING','READY'),'READY');
assert.throws(()=>E.transition('inbox','IDLE','READY'),/Illegal/);
assert.equal(E.transition('backup','READING','VALIDATING'),'VALIDATING');
assert.throws(()=>E.transition('backup','IDLE','DONE'),/Illegal/);
const paid={...receipt,key:'r',status:'PAID'};
const unreviewed={...receipt,key:'r2',status:'REVIEW',amount:100,date:'2026-11-09T15:00:00Z'};
const due={...receipt,key:'r3',status:'DUE',amount:45,date:'2026-11-10T15:00:00Z'};
const result=E.summary([paid,unreviewed,due],'2026-11');
assert.equal(result.groups.USD.detected,430);assert.equal(result.groups.USD.paid,285);assert.equal(result.groups.USD.due,45);assert.equal(result.reviewCount,1);
const changed=E.mergeCandidates([paid],[{...receipt,status:'REVIEW'}]);
assert.equal(changed.find(x=>x.key==='r').status,'PAID','manual review survives subsequent scans');
const duplicate=E.dedupe([{...receipt,key:'a'},{...receipt,key:'b'}]);assert.equal(duplicate[1].possibleDuplicateOf,'a');
const mixed=E.summary([paid,{...receipt,key:'rupee',currency:'INR',amount:500,status:'PAID'}],'2026-11');
assert.equal(mixed.groups.USD.paid,285);assert.equal(mixed.groups.INR.paid,500);
console.log('Passed finance classification, amount, duplicate, review, account and explicit state-contract tests.');
